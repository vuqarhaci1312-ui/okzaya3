function decodeMarkupEntities(html) {
  return String(html || '')
    .replace(/&Ccedil;/g, 'Ç')
    .replace(/&ccedil;/gi, 'ç')
    .replace(/&Uuml;/g, 'Ü')
    .replace(/&uuml;/gi, 'ü')
    .replace(/&Ouml;/g, 'Ö')
    .replace(/&ouml;/gi, 'ö')
    .replace(/&szlig;/gi, 'ß')
    .replace(/&ldquo;/gi, '"')
    .replace(/&rdquo;/gi, '"')
    .replace(/&lsquo;/gi, "'")
    .replace(/&rsquo;/gi, "'")
    .replace(/&deg;/gi, '°')
    .replace(/&ordm;/gi, '°')
    .replace(/&sup3;/gi, '³')
    .replace(/&sup2;/gi, '²')
    .replace(/&Oslash;/g, 'Ø')
    .replace(/&oslash;/gi, 'ø')
    .replace(/&reg;/gi, '®')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCharCode(parseInt(hex, 16)))
    .replace(/&amp;/g, '&');
}

function decodeEntities(text) {
  return decodeMarkupEntities(text)
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function applyPhrases(text) {
  let result = String(text || '');
  for (const [from, to] of PHRASES) {
    result = result.split(from).join(to);
  }
  return result;
}

function translateTrToAz(text) {
  return applyPhrases(decodeEntities(text));
}

function translateHtmlToAz(html) {
  return applyPhrases(decodeMarkupEntities(html));
}

module.exports = { decodeEntities, decodeMarkupEntities, translateTrToAz, translateHtmlToAz, PHRASES };
